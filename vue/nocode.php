<script>
async function loadNewsNoCode() {
  const container = document.getElementById("news-feed");
  if (!container) return;

  // ✅ Flux FR
  const rssUrls = [
    "https://www.journaldunet.com/rss/",
    "https://www.blogdumoderateur.com/feed/",
    "https://siecledigital.fr/feed/",
    "https://www.lemondeinformatique.fr/flux-rss/application/rss.xml"
  ];

  // ✅ Filtre strict Low-Code / No-Code
  const keywords = [
    "low-code", "low code",
    "no-code", "no code", "nocode",
    "power apps", "power platform", "copilot studio",
    "bubble", "webflow", "glide", "softr",
    "airtable", "notion",
    "make.com", "make ", "zapier", "n8n",
    "citizen developer", "automatisation", "workflow"
  ];

  const proxy = (url) => "https://api.allorigins.win/raw?url=" + encodeURIComponent(url);

  function getItemDate(item) {
    const pubDate = item.getElementsByTagName("pubDate")[0]?.textContent?.trim() || "";
    const dcDate  = item.getElementsByTagName("dc:date")[0]?.textContent?.trim() || "";
    const dateString = pubDate || dcDate;

    if (!dateString) return null;
    const d = new Date(dateString);
    return isNaN(d.getTime()) ? null : d;
  }

  function formatDateFR(d) {
    return d.toLocaleDateString("fr-FR", {
      day: "2-digit",
      month: "2-digit",
      year: "numeric"
    });
  }

  function extractImageAndText(descriptionHtml) {
    const tempDiv = document.createElement("div");
    tempDiv.innerHTML = descriptionHtml || "";

    let imgUrl = "assets/images/low-code-no-code.jpg"; // image par défaut locale
    const imgTag = tempDiv.querySelector("img");
    if (imgTag?.src) imgUrl = imgTag.src;

    const cleanText = (tempDiv.textContent || "").trim().replace(/\s+/g, " ");
    const cleanDesc = cleanText.length > 120 ? cleanText.slice(0, 120) + "..." : cleanText;

    return { imgUrl, cleanDesc };
  }

  function isLowNoCode(title, desc) {
    const t = (title || "").toLowerCase();
    const d = (desc || "").toLowerCase();
    return keywords.some(k => t.includes(k) || d.includes(k));
  }

  try {
    container.innerHTML = `<div class="col-12"><div class="alert alert-info">Chargement de la veille Low-Code / No-Code…</div></div>`;

    // ✅ Robuste : si un flux tombe, on affiche quand même le reste
    const results = await Promise.allSettled(
      rssUrls.map(async (url) => {
        const res = await fetch(proxy(url), { cache: "no-store" });
        return await res.text();
      })
    );

    const xmlTexts = results
      .filter(r => r.status === "fulfilled")
      .map(r => r.value);

    let allItems = [];

    xmlTexts.forEach((xmlText) => {
      const xml = new DOMParser().parseFromString(xmlText, "text/xml");
      const items = Array.from(xml.getElementsByTagName("item"));

      const channelTitle =
        xml.getElementsByTagName("channel")[0]?.getElementsByTagName("title")[0]?.textContent?.trim()
        || "Source";

      items.forEach((item) => {
        const title = item.getElementsByTagName("title")[0]?.textContent?.trim() || "Sans titre";
        const link  = item.getElementsByTagName("link")[0]?.textContent?.trim() || "#";
        const desc  = item.getElementsByTagName("description")[0]?.textContent || "";
        const date  = getItemDate(item);

        // ✅ On garde UNIQUEMENT le Low/No-Code
        if (!isLowNoCode(title, desc)) return;

        allItems.push({ title, link, desc, date, source: channelTitle });
      });
    });

    // Trier + garder les 4 dernières
    allItems.sort((a, b) => {
      if (!a.date && !b.date) return 0;
      if (!a.date) return 1;
      if (!b.date) return -1;
      return b.date - a.date;
    });

    const latest4 = allItems.slice(0, 4);

    container.innerHTML = "";

    if (latest4.length === 0) {
      container.innerHTML = `
        <div class="col-12">
          <div class="alert alert-warning">
            Aucune actualité Low-Code / No-Code trouvée avec les mots-clés actuels.
            <br>Astuce : ajoute des mots-clés (ex: "PowerApps", "Webflow", "Make") ou des flux plus ciblés.
          </div>
        </div>`;
      return;
    }

    latest4.forEach((news) => {
      const dateFinale = news.date ? formatDateFR(news.date) : "Récent";
      const { imgUrl, cleanDesc } = extractImageAndText(news.desc);

      container.innerHTML += `
        <div class="col-lg-6">
          <div class="project-card card h-100">
            <img src="${imgUrl}" class="card-img-top" alt="Low-Code / No-Code"
                 onerror="this.src='assets/images/low-code-no-code.jpg'">
            <div class="card-body">
              <h5>${news.title}</h5>
              <p class="text-muted">${dateFinale} • ${news.source}</p>
              <p>${cleanDesc}</p>
              <a href="${news.link}" target="_blank" class="btn btn-sm btn-warning text-dark">
                Lire l'article
              </a>
            </div>
          </div>
        </div>
      `;
    });

  } catch (err) {
    console.error("Erreur détaillée:", err);
    container.innerHTML = '<div class="alert alert-danger">Erreur de chargement.</div>';
  }
}

document.addEventListener("DOMContentLoaded", loadNewsNoCode);
</script>

