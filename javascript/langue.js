let currentLanguage = 'fr';

function setLanguage(lang) {
    currentLanguage = lang;

    // Appliquer les traductions pour les textes
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const data = element.getAttribute("data-i18n");

        data.split(";").forEach(item => {
            item = item.trim();

            // Cas attributs (ex: [placeholder]Votre email)
            const match = item.match(/^\[(.+)\](.+)$/);
            if (match) {
                const attr = match[1]; // placeholder / aria-label
                const key = match[2];  // ex: Votre email
                if (translations[lang] && translations[lang][key]) {
                    element.setAttribute(attr, translations[lang][key]);
                }
            } else {
                // Cas texte normal
                if (translations[lang] && translations[lang][item]) {
                    element.textContent = translations[lang][item];
                }
            }
        });
    });

    // Appliquer l'orientation RTL uniquement pour l'arabe
    if (lang === "ar") {
        document.body.setAttribute("dir", "rtl");
        document.body.classList.add("rtl");
    } else {
        document.body.setAttribute("dir", "ltr");
        document.body.classList.remove("rtl");
    }
}
